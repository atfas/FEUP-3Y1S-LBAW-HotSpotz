CREATE TABLE users (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    is_active BOOLEAN NOT NULL DEFAULT true,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    date_of_birth DATE NOT NULL,
    phone VARCHAR(20) CHECK (phone ~ '^\+[0-9]{1,3}[0-9]{4,14}$'),
    profile_picture_url TEXT CHECK (profile_picture_url IS NULL OR profile_picture_url <> ''),
    registration_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_blocked BOOLEAN NOT NULL DEFAULT false,
    is_admin BOOLEAN NOT NULL DEFAULT false,
    application_status VARCHAR(20) CHECK (application_status IN ('Pending', 'Approved', 'Rejected')) DEFAULT NULL,
    answers TEXT CHECK (answers <> ''),
    verification_docs TEXT,
    payout_details TEXT,
    submitted_at TIMESTAMP,
    verified_at TIMESTAMP,
    verifier_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    CHECK (
      registration_date::DATE >= date_of_birth
      AND (
        NOT is_active
        OR (
          full_name <> ''
          AND email ~ '^[A-Za-z0-9._+%-]+@[A-Za-z0-9.-]+[.][A-Za-z]+$'
          AND password_hash <> ''
          AND date_of_birth <= CURRENT_DATE - INTERVAL '18 years'
        )
      )
    ),
    CHECK (
      application_status IS NULL
      OR (
        answers IS NOT NULL
        AND verification_docs IS NOT NULL
        AND submitted_at IS NOT NULL
        AND submitted_at >= registration_date
      )
    ),
    CHECK (verifier_id IS NULL OR verifier_id <> id),
    CHECK (
      application_status <> 'Approved'
      OR (
        payout_details IS NOT NULL
        AND verified_at IS NOT NULL
        AND verified_at >= submitted_at
        AND verifier_id IS NOT NULL
      )
    )
);

CREATE TABLE admin_notification(
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    type VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE listings (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    max_occupancy INTEGER NOT NULL CHECK (max_occupancy >= 1) DEFAULT 1,
    location_address TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT true,
    minimum_stay INTEGER NOT NULL CHECK (minimum_stay >= 1) DEFAULT 1,
    cancellation_policy TEXT NOT NULL,
    amenities TEXT DEFAULT NULL,
    average_rating NUMERIC(3,2) NOT NULL DEFAULT 0,
    num_reviews INTEGER NOT NULL DEFAULT 0,
    host_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    CHECK (CASE WHEN is_active then (title <> '' AND description <> '' AND location_address <> '' AND cancellation_policy <> '') END),
    search_vector tsvector 
);

CREATE TABLE availability(
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL CHECK (end_date >= start_date),
    price_per_night NUMERIC(10,2) NOT NULL CHECK (price_per_night >= 0),
    check_in_time TIME NOT NULL,
    check_out_time TIME NOT NULL,
    listing_id INTEGER NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
    UNIQUE (start_date, end_date, listing_id)
);

CREATE TABLE tags (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(64) NOT NULL UNIQUE
);

CREATE TABLE listing_tags (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    tag_id INTEGER NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
    listing_id INTEGER NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
    UNIQUE(tag_id, listing_id)
);

CREATE TABLE listing_photos (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    url TEXT NOT NULL UNIQUE CHECK (url <> ''),
    caption TEXT,
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    listing_id INTEGER NOT NULL REFERENCES listings(id) ON DELETE CASCADE
);

CREATE TABLE bookings (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    check_in_date DATE NOT NULL,
    check_out_date DATE NOT NULL CHECK (check_out_date > check_in_date),
    num_guests INTEGER NOT NULL CHECK (num_guests >= 1) DEFAULT 1,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PendingPayment', 'Confirmed', 'Cancelled', 'Completed', 'Rejected')) DEFAULT 'PendingPayment',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total_price NUMERIC(10,2) NOT NULL CHECK (total_price >= 0),
    availability_id INTEGER NOT NULL REFERENCES availability(id) ON DELETE CASCADE,
    guest_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    UNIQUE (check_in_date, check_out_date, availability_id)
);

CREATE TABLE transactions (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    amount NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    transaction_method VARCHAR(20) NOT NULL CHECK (transaction_method IN ('Card', 'Bank Transfer', 'Paypal', 'Cash')),
    type VARCHAR(20) NOT NULL CHECK (type IN ('FullPayment', 'Refund')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('Pending', 'Completed', 'Failed', 'Refunded')) DEFAULT 'Pending',
    paid_at TIMESTAMP,
    refund_id INTEGER REFERENCES transactions(id) ON DELETE SET NULL,
    booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    CHECK (CASE WHEN status IN ('Completed', 'Refunded') then (paid_at IS NOT NULL) END)
);

CREATE TABLE reviews (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    rating INTEGER NOT NULL CHECK (rating >= 0 AND rating <= 5),
    comment TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    answer_content TEXT,
    answered_at TIMESTAMP,
    guest_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    host_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE UNIQUE,
    CHECK (CASE WHEN answered_at IS NOT NULL then (answer_content IS NOT NULL) END)
);

CREATE TABLE conversations (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    concluded_at TIMESTAMP,
    guest_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    host_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE CHECK (host_id <> guest_id),
    listing_id INTEGER REFERENCES listings(id) ON DELETE CASCADE,
    booking_id INTEGER REFERENCES bookings(id) ON DELETE CASCADE,
    CHECK ((listing_id IS NOT NULL AND booking_id IS NULL) OR (listing_id IS NULL AND booking_id IS NOT NULL)),
    UNIQUE (guest_id, host_id, listing_id, booking_id)
);

CREATE TABLE messages (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    author VARCHAR(10) NOT NULL CHECK (author IN ('Guest', 'Host')),
    content TEXT NOT NULL CHECK (content <> ''),
    send_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attachments TEXT CHECK (attachments IS NULL OR attachments <> ''),
    is_read BOOLEAN NOT NULL DEFAULT false,
    conversation_id INTEGER NOT NULL REFERENCES conversations(id) ON DELETE CASCADE
);

CREATE TABLE notifications (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    type VARCHAR(30) NOT NULL CHECK (type IN ('BookingConfirmed', 'BookingCanceled', 'PaymentReceived', 'Remainder', 'MessageReceived', 'ReviewLeft', 'AdminNotice')),
    content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_read BOOLEAN NOT NULL DEFAULT false,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    admin_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    admin_notification_id INTEGER REFERENCES admin_notification(id) ON DELETE SET NULL,
    booking_id INTEGER REFERENCES bookings(id) ON DELETE SET NULL,
    transaction_id INTEGER REFERENCES transactions(id) ON DELETE SET NULL,
    message_id INTEGER REFERENCES messages(id) ON DELETE SET NULL,
    review_id INTEGER REFERENCES reviews(id) ON DELETE SET NULL,
    CHECK(CASE WHEN type IN ('BookingConfirmed', 'BookingCanceled', 'Remainder') then (booking_id IS NOT NULL) END),
    CHECK(CASE WHEN type IN ('PaymentReceived') then (transaction_id IS NOT NULL) END),
    CHECK(CASE WHEN type IN ('MessageReceived') then (message_id IS NOT NULL) END),
    CHECK(CASE WHEN type IN ('ReviewLeft') then (review_id IS NOT NULL) END),
    CHECK(CASE WHEN type IN ('AdminNotice') then (admin_id IS NOT NULL AND admin_notification_id IS NOT NULL) END)
);

