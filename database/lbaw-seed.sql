CREATE OR REPLACE FUNCTION refresh_listing_search_vector_from_review()
RETURNS trigger AS $$
DECLARE
    listing_id_val INTEGER;
BEGIN
    SELECT a.listing_id INTO listing_id_val
    FROM bookings b
    JOIN availability a ON a.id = b.availability_id
    WHERE b.id = NEW.booking_id;

    UPDATE listings
    SET search_vector =
        setweight(to_tsvector('english', coalesce(title, '') || ' ' || coalesce(description, '') || ' ' || coalesce(location_address, '')), 'A') ||
        setweight(to_tsvector('english', coalesce(
            (SELECT string_agg(comment, ' ')
             FROM reviews r
             JOIN availability a2 ON a2.listing_id = listings.id
             JOIN bookings b2 ON b2.availability_id = a2.id
             WHERE r.booking_id = b2.id), ''
        )), 'B') ||
        setweight(to_tsvector('english', coalesce(
            (SELECT string_agg(answer_content, ' ')
             FROM reviews r
             JOIN availability a3 ON a3.listing_id = listings.id
             JOIN bookings b3 ON b3.availability_id = a3.id
             WHERE r.booking_id = b3.id), ''
        )), 'C')
    WHERE id = listing_id_val;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_refresh_listing_search_vector_from_review
    AFTER INSERT OR UPDATE OR DELETE ON reviews
    FOR EACH ROW
    EXECUTE FUNCTION refresh_listing_search_vector_from_review();

