CREATE TABLE users (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    is_active BOOLEAN NOT NULL DEFAULT true,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    date_of_birth DATE NOT NULL,
    phone VARCHAR(20) CHECK (phone ~ '^\+[0-9]{1,3}[0-9]{4,14}$'),
    profile_picture_url TEXT CHECK (profile_picture_url IS NULL OR profile_picture_url <> ''),
    registration_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_blocked BOOLEAN NOT NULL DEFAULT false,
    is_admin BOOLEAN NOT NULL DEFAULT false,
    application_status VARCHAR(20) CHECK (application_status IN ('Pending', 'Approved', 'Rejected')) DEFAULT NULL,
    answers TEXT CHECK (answers <> ''),
    verification_docs TEXT,
    payout_details TEXT,
    submitted_at TIMESTAMP,
    verified_at TIMESTAMP,
    verifier_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    CHECK (
      registration_date::DATE >= date_of_birth
      AND (
        NOT is_active
        OR (
          full_name <> ''
          AND email ~ '^[A-Za-z0-9._+%-]+@[A-Za-z0-9.-]+[.][A-Za-z]+$'
          AND password_hash <> ''
          AND date_of_birth <= CURRENT_DATE - INTERVAL '18 years'
        )
      )
    ),
    CHECK (
      application_status IS NULL
      OR (
        answers IS NOT NULL
        AND verification_docs IS NOT NULL
        AND submitted_at IS NOT NULL
        AND submitted_at >= registration_date
      )
    ),
    CHECK (verifier_id IS NULL OR verifier_id <> id),
    CHECK (
      application_status <> 'Approved'
      OR (
        payout_details IS NOT NULL
        AND verified_at IS NOT NULL
        AND verified_at >= submitted_at
        AND verifier_id IS NOT NULL
      )
    )
);

