CREATE OR REPLACE FUNCTION check_booking_constraints()
RETURNS TRIGGER AS $$
DECLARE
    _listing_id INTEGER;
    _availability_start_date DATE;
    _availability_end_date DATE;
    _host_id INTEGER;
BEGIN
    SELECT a.listing_id, a.start_date, a.end_date, l.host_id
    INTO _listing_id, _availability_start_date, _availability_end_date, _host_id
    FROM availability a
    JOIN listings l ON a.listing_id = l.id
    WHERE a.id = NEW.availability_id;

    IF NEW.guest_id = _host_id THEN
        RAISE EXCEPTION 'Guest cannot book their own listing.';
    END IF;

    IF NEW.check_in_date < _availability_start_date OR NEW.check_out_date > _availability_end_date THEN
        RAISE EXCEPTION 'Booking dates must be within the associated availability range.';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM bookings b
        JOIN availability a ON b.availability_id = a.id
        WHERE a.listing_id = _listing_id
          AND b.id <> NEW.id
          AND b.status IN ('PendingPayment', 'Confirmed')
          AND (NEW.check_in_date, NEW.check_out_date) OVERLAPS (b.check_in_date, b.check_out_date)
    ) THEN
        RAISE EXCEPTION 'New booking overlaps with an existing confirmed or pending booking for the same listing.';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_check_booking_constraints
    BEFORE INSERT OR UPDATE ON bookings
    FOR EACH ROW
    EXECUTE FUNCTION check_booking_constraints();

