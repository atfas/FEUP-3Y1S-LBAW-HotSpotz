CREATE OR REPLACE FUNCTION listings_search_vector_update()
RETURNS trigger AS $$
BEGIN
    NEW.search_vector :=
        setweight(to_tsvector('english', coalesce(NEW.title, '') || ' ' || coalesce(NEW.description, '') || ' ' || coalesce(NEW.location_address, '')), 'A');
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

